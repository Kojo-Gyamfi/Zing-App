// Generates components/chat/emojiKeywords.ts: the words each emoji in the picker
// can be found by (its CLDR name, tags and common shortcodes, from emojibase-data),
// for the emoji search. Only the emoji the picker shows, so the file stays small.
// Run after changing components/chat/emojiData.ts:
//   node scripts/gen-emoji-keywords.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const compact = require('emojibase-data/en/compact.json');
const shortcodeSets = [
  require('emojibase-data/en/shortcodes/cldr.json'),
  require('emojibase-data/en/shortcodes/emojibase.json'),
  require('emojibase-data/en/shortcodes/github.json'),
];

// Variation selectors differ between sources (☺ vs ☺️); match without them.
const bare = (emoji) => emoji.replace(/️/g, '');

const byEmoji = new Map();
for (const entry of compact) byEmoji.set(bare(entry.unicode), entry);

// The picker's own list, read from its source so the two can't drift apart.
const source = readFileSync(new URL('../components/chat/emojiData.ts', import.meta.url), 'utf8');
const catalogue = [...source.matchAll(/list\(`([^`]*)`\)/g)].flatMap((match) => match[1].trim().split(/\s+/));

const lines = [];
const missing = [];
for (const emoji of new Set(catalogue)) {
  const entry = byEmoji.get(bare(emoji));
  if (!entry) {
    missing.push(emoji);
    continue;
  }
  const words = new Set(entry.label.toLowerCase().split(/[\s:,]+/).filter(Boolean));
  for (const tag of entry.tags ?? []) for (const word of tag.toLowerCase().split(/\s+/)) words.add(word);
  for (const set of shortcodeSets) {
    const codes = set[entry.hexcode];
    for (const code of [codes ?? []].flat()) for (const word of code.toLowerCase().split(/[_-]+/)) words.add(word);
  }
  const label = entry.label.toLowerCase();
  lines.push(`  [${JSON.stringify(emoji)}, ${JSON.stringify(label)}, ${JSON.stringify([...words].join(' '))}],`);
}

writeFileSync(
  new URL('../components/chat/emojiKeywords.ts', import.meta.url),
  `// Generated by scripts/gen-emoji-keywords.mjs from emojibase-data (Unicode CLDR). Do not edit.
// Bundled, never fetched: what someone searches for stays on their device.

/** [emoji, name, words it can be found by] in the picker's order. */
export const EMOJI_KEYWORDS: [emoji: string, name: string, words: string][] = [
${lines.join('\n')}
];
`,
);
console.log(`${lines.length} emoji written${missing.length ? `; no data for ${missing.join(' ')}` : ''}`);
